import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

export async function testCampaigns(db, { org, owner, staff, event, sibling, other, program, scalar, role, fails }) {
  await db.exec(`create function public.is_org_member(org uuid) returns boolean language sql stable security definer set search_path=public as $$select exists(select 1 from memberships where organization_id=org and user_id=auth.uid())$$;
    alter table event_participations add column created_at timestamptz default now(), add column participation_type text, add column source text;
    alter table event_participations add unique(program_id,person_id,event_id,participation_type);
    alter table people alter column id set default gen_random_uuid();
    alter table people add column phone text, add column cedula text, add column company text, add column job_title text, add column city text, add column country text, add column profile_data jsonb;
    alter table people add unique(organization_id,email);
    alter table passes add column program_id uuid, add column is_public boolean default true, add column capacity int;
    alter table participation_passes add unique(participation_id,pass_id);`);
  const programMigration = await readFile(new URL('../infra/supabase/migrations/20260827155000_p0_program_credentials.sql', import.meta.url), 'utf8');
  await db.exec(programMigration.slice(programMigration.indexOf('create function public.register_program_participant('), programMigration.indexOf('revoke all on function public.register_program_participant')));
  const migration = await readFile(new URL('../infra/supabase/migrations/20261001183330_event_campaign_attribution.sql', import.meta.url), 'utf8');
  await db.exec(migration); await db.exec(migration);
  await role('authenticated', owner);
  const campaign = await scalar(`select create_event_campaign($1,'Instagram QA','instagram','paid_social',null)`, [sibling]);
  await fails(`select create_event_campaign($1,'Other','instagram','social',null)`, [other], /permiso/);
  const targets = await scalar(`select event_promotion_destinations($1)`, [sibling]);
  assert.match(targets[0].url, /\/evento\//);
  await role('authenticated', staff);
  await fails(`select create_event_campaign($1,'Staff','instagram','social',null)`, [sibling], /permiso/);
  await role('anon');
  await fails(`select get_event_campaign_dashboard($1)`, [sibling], /permission denied/);
  await fails(`select * from event_funnel_visits`, [], /permission denied/);
  const paidVisit = '10000000-0000-0000-0000-000000000001';
  const directVisit = '10000000-0000-0000-0000-000000000002';
  const formVisit = '10000000-0000-0000-0000-000000000003';
  const expiredVisit = '10000000-0000-0000-0000-000000000004';
  await scalar(`select track_event_visit($1,$2,'landing',$3,'spoofed','spoofed',null)`, [paidVisit, sibling, campaign]);
  await scalar(`select track_event_visit($1,$2,'landing',null,'direct',null,null)`, [paidVisit, sibling]);
  await scalar(`select track_event_visit($1,$2,'form',null,'direct',null,null)`, [paidVisit, sibling]);
  await fails(`select track_event_visit($1,$2,'landing')`, [paidVisit, other], /otro evento/);
  await fails(`select track_event_visit($1,$2,'completed')`, [paidVisit, sibling], /inválida/);
  await scalar(`select register_event_attributed_purchase($1,'Campaign','','campaign@example.test','1234567',null,null,null,$2)`, [sibling, paidVisit]);
  await fails(`select register_event_attributed_purchase($1,'Campaign','','campaign@example.test','1234567',null,null,null,$2)`, [sibling, paidVisit], /Ya existe/);
  await scalar(`select track_event_visit($1,$2,'landing')`, [directVisit, sibling]);
  await scalar(`select track_event_visit($1,$2,'form')`, [directVisit, sibling]);
  await scalar(`select register_event_attributed_purchase($1,'Direct','','direct@example.test','1234567',null,null,null,$2)`, [sibling, directVisit]);
  await scalar(`select track_event_visit($1,$2,'form')`, [formVisit, sibling]);
  await scalar(`select register_event_attributed_purchase($1,'Form','','form@example.test','1234567',null,null,null,$2)`, [sibling, formVisit]);
  await scalar(`select track_event_visit($1,$2,'landing')`, [formVisit, sibling]); // Cannot retroactively claim a landing visit.
  await scalar(`select track_event_visit($1,$2,'landing')`, [expiredVisit, sibling]);
  await role('service_role');
  await db.query(`update event_funnel_visits set created_at=now()-interval '31 minutes' where id=$1`, [expiredVisit]);
  await role('anon');
  await scalar(`select register_event_attributed_purchase($1,'Expired','','expired@example.test','1234567',null,null,null,$2)`, [sibling, expiredVisit]);
  await role('authenticated', owner);
  const report = await scalar(`select get_event_campaign_dashboard($1)`, [sibling]);
  assert.deepEqual(report.totals, { visits: 3, starts: 2, completions: 2, form_only: 1 });
  const campaignCounts = report.breakdown.find(row => row.campaign_id === campaign);
  assert.equal(campaignCounts.source, 'instagram'); assert.equal(campaignCounts.medium, 'paid_social'); assert.equal(campaignCounts.completions, 1);
  await scalar(`select archive_event_campaign($1,true)`, [campaign]);
  assert.equal((await scalar(`select get_event_campaign_dashboard($1)`, [sibling])).campaigns[0].archived, true);
  assert.equal((await scalar(`select get_event_campaign_dashboard($1,now()+interval '1 day')`, [sibling])).totals.visits, 0);
  await fails(`select get_event_campaign_dashboard($1)`, [other], /permiso/);
  // Shared-program landing keeps the promoted event, not an arbitrary linked event.
  await db.exec('reset role');
  const site = await scalar(`select id from public_sites where program_id=$1`, [program]);
  await db.query(`update public_sites set status='active',slug='campaign-qa' where id=$1`, [site]);
  await role('authenticated', owner);
  const shared = await scalar(`select create_event_campaign($1,'Shared','linkedin','social',$2)`, [sibling, site]);
  assert.equal((await scalar(`select event_promotion_destinations($1)`, [sibling]))[0].program_id, program);
  await role('anon');
  await scalar(`select track_event_visit($1,$2,'landing',$3,'linkedin','social',$4)`, ['10000000-0000-0000-0000-000000000005', sibling, shared, program]);
  await fails(`select track_event_visit($1,$2,'landing',null,null,null,$3)`, ['10000000-0000-0000-0000-000000000006', other, program], /ajeno/);
  await db.exec('reset role');
  const pass = '10000000-0000-0000-0000-000000000020';
  await db.query(`insert into passes(id,name,program_id) values($1,'General',$2)`, [pass,program]);
  await role('anon');
  await scalar(`select register_program_attributed_participant($1,$2,$3,'Program','','program@example.test','1234567',p_visit_id=>$4)`, [program,sibling,pass,'10000000-0000-0000-0000-000000000005']);
  await role('authenticated', owner);
  const sharedReport = await scalar(`select get_event_campaign_dashboard($1)`, [sibling]);
  assert.equal(sharedReport.breakdown.find(row => row.campaign_id === shared).completions, 1);
  await role('anon');
  const retryVisit = '10000000-0000-0000-0000-000000000007';
  await scalar(`select track_event_visit($1,$2,'landing',$3,'linkedin','social',$4)`, [retryVisit,sibling,shared,program]);
  await scalar(`select register_program_attributed_participant($1,$2,$3,'Program','','program@example.test','1234567',p_visit_id=>$4)`, [program,sibling,pass,retryVisit]);
  await role('authenticated', owner);
  assert.equal((await scalar(`select get_event_campaign_dashboard($1)`, [sibling])).breakdown.find(row => row.campaign_id === shared).completions, 1);
  await db.exec('reset role');
  console.log('PASS: campaign permissions/isolation, destinations, immutable attribution, deduplication, atomic conversions, duplicate rejection, form-only separation, expiry, period filters, shared program scope.');
}
