import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createServer } from '../frontend/node_modules/vite/dist/node/index.js'
import { chromium } from '../frontend/node_modules/@playwright/test/index.mjs'

const root = fileURLToPath(new URL('../frontend/', import.meta.url))
let server, browser
try {
  server = await createServer({ root, define: { 'import.meta.env.VITE_SUPABASE_URL': JSON.stringify('https://public-manual-qa.supabase.co'), 'import.meta.env.VITE_SUPABASE_ANON_KEY': JSON.stringify('manual-qa') }, server: { host: '127.0.0.1', port: 4191, strictPort: true, hmr: false } })
  await server.listen()
  browser = await chromium.launch({ channel: 'chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
  let commercialCalls = 0
  await context.route('https://public-manual-qa.supabase.co/**', route => { if (route.request().url().includes('public_commercial_catalog')) commercialCalls++; return route.fulfill({ json: [] }) })
  await context.addInitScript(() => { if (!localStorage.getItem('ef-manual-progress')) localStorage.setItem('ef-manual-progress', JSON.stringify(['done-3', 'done-12'])) })
  const page = await context.newPage(), errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:4191/manual/index.html')
  await page.locator('#done-eventos').waitFor()
  assert.equal(await page.locator('.chapter').count(), 27)
  assert.equal(await page.locator('#chapterCount').innerText(), '27')
  assert.equal(await page.locator('#screenCount').innerText(), '40')
  assert.equal(await page.locator('#roleCount').innerText(), '6')
  assert.equal(await page.locator('#done-eventos').isChecked(), true)
  assert.equal(await page.locator('#done-checkin').isChecked(), true)
  assert.equal(await page.locator('#done-organizacion').isChecked(), false)
  const sources = await page.locator('.shot img').evaluateAll(imgs => [...new Set(imgs.map(img => img.getAttribute('src')))])
  await Promise.all(sources.map(async path => { const response = await context.request.get('http://127.0.0.1:4191/manual/' + path); assert.equal(response.status(), 200, path); const bytes = await response.body(); assert.ok(bytes.subarray(1, 4).toString() === 'PNG' || (bytes[0] === 255 && bytes[1] === 216), path) }))
  await page.getByRole('searchbox', { name: 'Buscar en el manual' }).fill('conector')
  assert.equal(await page.locator('#centro-impresion').isVisible(), true)
  assert.equal(await page.locator('#eventos').isVisible(), false)
  await page.getByRole('searchbox', { name: 'Buscar en el manual' }).fill('')
  await page.locator('[data-role="collaborator"]').click()
  assert.equal(await page.locator('#portal-colaborador').isVisible(), true)
  assert.equal(await page.locator('#presupuesto').isVisible(), false)
  assert.equal(await page.locator('#mobileNav option[value="#presupuesto"]').isDisabled(), true)
  await page.locator('[data-role="all"]').click()
  await page.locator('#done-centro-impresion').check()
  await page.reload()
  assert.equal(await page.locator('#done-centro-impresion').isChecked(), true)
  await page.getByRole('button', { name: 'Ampliar Descarga e instalación del conector local', exact: true }).click()
  await page.locator('#lightboxImg').evaluate(img => img.decode())
  assert.equal(await page.getByRole('dialog').isVisible(), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').isVisible(), false)
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true })
  await page.goto('http://127.0.0.1:4191/manual/index.html')
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/manual-updated-desktop.png', import.meta.url)) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('#mobileNav').selectOption('#sociales')
  await page.locator('#sociales').scrollIntoViewIfNeeded()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/manual-updated-mobile.png', import.meta.url)) })
  await page.goto('http://127.0.0.1:4191/')
  await page.getByRole('heading', { name: 'Una opción para cada evento' }).waitFor()
  const plans = page.locator('#planes')
  assert.equal(await plans.locator('article').count(), 3)
  assert.doesNotMatch(await plans.innerText(), /\$|USD|\/mes|14 días|50 participantes/)
  assert.equal(await plans.getByRole('link', { name: 'Conversar sobre mi evento' }).count(), 3)
  assert.equal(commercialCalls, 0)
  assert.deepEqual(errors, [])
  console.log('PASS: 27 chapters, 40 images, six roles, search, mobile navigation, image zoom, progress migration and persistence; landing has three generic options, no prices and no commercial catalog request')
} finally { await browser?.close(); await server?.close() }
